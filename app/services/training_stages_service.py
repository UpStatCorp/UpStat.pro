# Первый этап каждой «продуктовой» тренировки начинается с подготовки: студент
# выбирает свой реальный товар/услугу, диктует список возражений, перечисляет
# факты о себе и т.д. Этапы 2-4 должны работать РОВНО с этими данными, иначе
# ИИ придумывает товар заново и тренировка теряет смысл.
#
# Azure Voice Live сохраняет историю диалога при session.update, так что
# формально ИИ «помнит» сказанное в первом этапе. Но в длинной сессии начало
# вытесняется, а формулировки возражений ИИ переписывает по-своему. Поэтому
# данные снимаются явно — через tool-функцию save_training_context — и
# подставляются в начало промпта каждого следующего этапа.

