# Составные тренировки: одна тренировка в интерфейсе = несколько блоков
# промптов подряд, по 4 этапа каждый.
#
# «Работа с возражениями» устроена как три последовательные тренировки:
# сначала механика подтверждения на бытовом примере, потом та же техника на
# реальном товаре студента, потом — на его собственной несовершённой покупке.
# Разрывать их на три отдельные тренировки в UI нельзя: смысл именно в
# переходе от простого примера к своему товару за одну сессию.
TRAINING_SEQUENCES = {
    "objections": [
        ("objections", "Подтверждение на простом примере"),
        ("real_objections", "Возражения по своему товару"),
        ("sale_objections", "Свои личные возражения"),
    ],
}


def get_sequence(stage_name: Optional[str]) -> List[tuple]:
    """
    Возвращает список блоков (slug, название) для тренировки.

    Для обычных тренировок это один блок с ней самой — вызывающий код
    не различает составные и простые тренировки.
    """
    if not stage_name:
        return []
    slug = stage_name.strip().lower()
    return TRAINING_SEQUENCES.get(slug) or [(slug, "")]


# Максимальные длины — защита от того, что ИИ вернёт в аргументах простыню
# и она попадёт в промпт каждого следующего этапа.
_MAX_STRING_LEN = 400
_MAX_ITEM_LEN = 300


def get_context_schema(stage_name: Optional[str]) -> Optional[List[ContextField]]:
    """Возвращает схему контекста для тренировки или None, если она не нужна."""
    if not stage_name:
        return None
    return TRAINING_CONTEXT_SCHEMAS.get(stage_name.strip().lower())


def build_save_context_tool(stage_name: Optional[str]) -> Optional[dict]:
    """
    Собирает определение tool-функции save_training_context под конкретную
    тренировку — с полями ровно из её схемы, чтобы ИИ не гадал, что сохранять.
    """
    schema = get_context_schema(stage_name)
    if not schema:
        return None

    properties = {}
    required = []
    for field in schema:
        if field.kind == "list":
            if field.item_fields:
                item_schema = {
                    "type": "object",
                    "properties": {
                        key: {"type": "string", "description": label}
                        for key, label in field.item_fields
                    },
                    "required": [key for key, _ in field.item_fields],
                }
            else:
                item_schema = {"type": "string"}
            properties[field.name] = {
                "type": "array",
                "description": field.description,
                "items": item_schema,
            }
        else:
            properties[field.name] = {"type": "string", "description": field.description}
        if field.required:
            required.append(field.name)

    return {
        "type": "function",
        "name": TOOL_SAVE_CONTEXT,
        "description": (
            "Сохраняет подготовительные данные тренировки, чтобы система передала их "
            "в следующие этапы. Вызови ОДИН раз в ПЕРВОМ этапе — сразу после того как "
            "пользователь назвал все нужные данные и ты повторил их вслух для сверки. "
            "Вызывай ДО complete_stage, отдельным вызовом. Передавай формулировки "
            "пользователя как есть, не переписывай их своими словами. "
            "В этапах 2, 3, 4 эту функцию вызывать НЕЛЬЗЯ."
        ),
        "parameters": {
            "type": "object",
            "properties": properties,
            "required": required,
        },
    }


def render_save_context_instruction(stage_name: Optional[str]) -> str:
    """
    Собирает инструкцию для ИИ о вызове save_training_context в первом этапе.

    Генерируется из той же схемы, что и сама tool-функция — иначе список полей
    в промпте и в аргументах функции разъезжаются при любой правке.
    """
    schema = get_context_schema(stage_name)
    if not schema:
        return ""

    lines = [
        "",
        "",
        "===== СОХРАНЕНИЕ ДАННЫХ ДЛЯ СЛЕДУЮЩИХ ЭТАПОВ =====",
        "Данные, которые ты собрал в подготовительной части этого этапа, нужны в этапах 2, 3 и 4.",
        f"Как только пользователь всё назвал и ты повторил это вслух для сверки — вызови функцию {TOOL_SAVE_CONTEXT}",
        "и передай в неё:",
    ]
    for field in schema:
        mark = "обязательно" if field.required else "если пользователь это дал"
        lines.append(f"* {field.name} — {field.description} ({mark})")
    lines += [
        "",
        "Формулировки передавай СЛОВАМИ ПОЛЬЗОВАТЕЛЯ, не переписывай их и не улучшай.",
        f"Вызов {TOOL_SAVE_CONTEXT} беззвучный — пользователь его не слышит, комментировать его вслух не нужно.",
        f"Вызови его ОДИН раз и ДО complete_stage.",
        "==================================================",
        "",
    ]
    return "\n".join(lines)


def normalize_training_context(stage_name: Optional[str], raw: dict) -> Optional[dict]:
    """
    Приводит аргументы вызова save_training_context к нормальному виду:
    отбрасывает чужие ключи, режет длины и количество элементов, выкидывает пустое.

    Returns:
        Словарь с данными или None, если обязательные поля не заполнены —
        в этом случае контекст не сохраняется и этапы 2-4 работают
        по своей ветке «если контекст не передан, восстанови его».
    """
    schema = get_context_schema(stage_name)
    if not schema or not isinstance(raw, dict):
        return None

    result: dict = {}
    for field in schema:
        value = raw.get(field.name)

        if field.kind == "list":
            if not isinstance(value, list):
                continue
            items = []
            for item in value:
                if field.item_fields and isinstance(item, dict):
                    normalized = {
                        key: str(item.get(key) or "").strip()[:_MAX_ITEM_LEN]
                        for key, _ in field.item_fields
                    }
                    if any(normalized.values()):
                        items.append(normalized)
                elif not field.item_fields:
                    text = str(item or "").strip()[:_MAX_ITEM_LEN]
                    if text:
                        items.append(text)
            if field.max_items:
                items = items[: field.max_items]
            if items:
                result[field.name] = items
        else:
            text = str(value or "").strip()[:_MAX_STRING_LEN]
            if text:
                result[field.name] = text

    # Обязательное поле-список считаем заполненным только при min_items элементов:
    # список из одного возражения сделает этапы 2-4 бессмысленными.
    for field in schema:
        if not field.required:
            continue
        value = result.get(field.name)
        if not value:
            logger.warning(
                "⚠️ save_training_context('%s'): не заполнено обязательное поле '%s' — "
                "контекст не сохраняем", stage_name, field.name
            )
            return None
        if field.kind == "list" and field.min_items and len(value) < field.min_items:
            logger.warning(
                "⚠️ save_training_context('%s'): в поле '%s' только %d элементов "
                "(нужно минимум %d) — контекст не сохраняем",
                stage_name, field.name, len(value), field.min_items
            )
            return None

    result["training_slug"] = stage_name
    return result


def render_context_block(stage_name: Optional[str], context: Optional[dict]) -> str:
    """
    Разворачивает сохранённый контекст в текстовый блок, который подставляется
    в НАЧАЛО промпта этапов 2-4.

    Возвращает пустую строку, если контекста нет — тогда промпт этапа уходит
    как есть, и ИИ отработает по своей ветке восстановления контекста вопросом.
    """
    schema = get_context_schema(stage_name)
    if not schema or not context:
        return ""

    lines = [
        "===== КОНТЕКСТ ТЕКУЩЕЙ ТРЕНИРОВКИ =====",
        "Эти данные пользователь уже назвал ранее в этой тренировке.",
        "Используй их как есть и НЕ спрашивай их заново.",
        "",
    ]
    has_values = False

    for field in schema:
        value = context.get(field.name)
        if not value:
            continue
        has_values = True
        if field.kind == "list":
            lines.append(f"{field.label}:")
            for index, item in enumerate(value, start=1):
                if field.item_fields and isinstance(item, dict):
                    parts = [
                        f"{label}: {item.get(key)}"
                        for key, label in field.item_fields
                        if item.get(key)
                    ]
                    lines.append(f"{index}. " + "; ".join(parts))
                else:
                    lines.append(f"{index}. {item}")
            lines.append("")
        else:
            lines.append(f"{field.label}: {value}")

    if not has_values:
        return ""

    lines.append("========================================")
    return "\n".join(lines).replace("\n\n\n", "\n\n") + "\n\n"


def _trainings_root() -> Path:
    """Возвращает корневую папку с промптами этапов тренировок."""
    return Path(__file__).resolve().parent.parent / "static" / "docs" / "trainings"


@dataclass
class TrainingStage:
    """Описание одного этапа тренировки."""
    number: int
    prompt: str
    ai_role: str
    ai_role_description: str
    training_type: str
    # Шаблон ПЕРВОЙ реплики этапа — передаётся в триггер response.create
    # при переходе, чтобы ИИ сразу выдал согласованную с промптом вступительную
    # фразу, а не импровизировал. Содержит несколько примеров через "ИЛИ".
    first_line_template: str = ""

    # Составные тренировки (см. TRAINING_SEQUENCES) склеены из нескольких
    # блоков по 4 этапа. Поля ниже описывают, из какого блока пришёл этап:
    #   source_slug     — папка промптов ("objections", "real_objections", ...);
    #                     по ней же определяется схема контекста и tools;
    #   number_in_block — номер этапа ВНУТРИ блока (1-4), как в тексте промпта;
    #   block_index/block_total/block_title — положение блока в тренировке.
    # Для обычных тренировок source_slug равен имени тренировки, а блок один.
    source_slug: str = ""
    number_in_block: int = 0
    block_index: int = 1
    block_total: int = 1
    block_title: str = ""


# Часть файлов этапов начинается с блока «Инструкция программисту» — описания
# JSON-контекста и того, как его передавать между этапами. Это адресовано нам,
# а не ИИ: попав в промпт, такой блок сбивает роль и иногда зачитывается вслух.
# Вырезаем всё до заголовка «ИНФОРМАЦИЯ ОБ ЭТАПЕ», но только если в отрезанной
# части действительно техническая инструкция, а не подзаголовок промпта.
_PREAMBLE_MARKERS = re.compile(
    r"Инструкция\s+программисту|\"training_slug\"|Что нужно сохранять в базу|\{\{",
    re.IGNORECASE,
)


def _strip_programmer_preamble(text: str, source: str = "") -> str:
    """Убирает из промпта этапа вводный блок, адресованный разработчику."""
    match = re.search(r"ИНФОРМАЦИЯ\s+ОБ\s+ЭТАПЕ", text)
    if not match or match.start() == 0:
        return text
    preamble = text[: match.start()]
    if not _PREAMBLE_MARKERS.search(preamble):
        return text
    logger.info(
        "✂️ %s: вырезан блок инструкции программисту (%d символов) перед промптом этапа",
        source or "промпт этапа", len(preamble),
    )
    return text[match.start():]


def _parse_stage_metadata(prompt: str, number: int) -> TrainingStage:
    """
    Достаёт мета-информацию об этапе (роль ИИ, тип тренировки) из текста промпта.

    Промпт должен содержать блок:
        ИНФОРМАЦИЯ ОБ ЭТАПЕ:
        * Номер этапа: ...
        * Роль ИИ: ...
        * Тип тренировки: ...
        * Роль пользователя (напарника): ...
    """
    ai_role = "Тренер"
    training_type = ""

    role_match = re.search(r"Роль\s+ИИ\s*:\s*(.+)", prompt)
    if role_match:
        ai_role = role_match.group(1).strip().split("\n")[0].strip()

    type_match = re.search(r"Тип\s+тренировки\s*:\s*(.+)", prompt)
    if type_match:
        training_type = type_match.group(1).strip().split("\n")[0].strip()

    role_short = ai_role.split("(")[0].strip()
    if "клиент" in role_short.lower():
        role_short = "Клиент"
    elif "менеджер" in role_short.lower():
        role_short = "Менеджер по продажам"

    description_parts = []
    if training_type:
        description_parts.append(training_type)
    description = " · ".join(description_parts)

    return TrainingStage(
        number=number,
        prompt=prompt,
        ai_role=role_short,
        ai_role_description=description,
        training_type=training_type,
    )


